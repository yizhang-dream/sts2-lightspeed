void applyAscensionToMonsterDefs(int level) {
    std::vector<MonsterDef>& defs = BattleContext::monsterDefsForAscension();
    if (g_pristine == nullptr) g_pristine = new PristineDefs{defs};
    defs = g_pristine->defs;

    std::vector<std::string> problems;
    if (level >= 8) {
        for (const AscHpOverride& o : kAscHp) {
            MonsterDef* d = findDef(defs, o.name);
            if (!d) { problems.push_back(std::string("hp: no def ") + o.name); continue; }
            if (d->minHp != o.minBase || d->maxHp != o.maxBase) {
                problems.push_back(std::string("hp base drift ") + o.name);
                continue;
            }
            d->minHp = o.minHi;
            d->maxHp = o.maxHi;
        }
    }
    static const int kStateFields[7] = {0, 1, 2, 3, 4, 5, 6};
    for (const AscValOverride& o : kAscVal) {
        if (o.level == 8 ? level < 8 : level < 9) continue;
        MonsterDef* d = findDef(defs, o.name);
        if (!d) { problems.push_back(std::string("val: no def ") + o.name); continue; }
        if (o.field >= 7 || (o.move[0] != '\0' && o.field >= 0)) {
            // exact target: named move + classified field (def-level ids 7-9 apply to
            // the def itself, with or without a move id)
            if (o.field <= 6 || o.field >= 10) {
                MoveState* st = nullptr;
                for (auto& s : d->states)
                    if (std::strcmp(s.moveId, o.move) == 0) { st = &s; break; }
                if (!st) { problems.push_back(std::string("val: no move ") + o.name + "/" + o.move); continue; }
                int* p = fieldPtr(*st, o.field);
                if (*p != o.base) {
                    problems.push_back(std::string("val base drift ") + o.name + "/" + o.move);
                    continue;
                }
                *p = o.hi;
            } else {
                int* p = defFieldPtr(*d, o.field);
                if (!p || *p != o.base) {
                    problems.push_back(std::string("val base drift ") + o.name + "/def");
                    continue;
                }
                *p = o.hi;
            }
        } else {
            // value match across the whitelisted state + def fields; every hit equal to
            // base is bumped. Skipped when another entry maps the same base to a
            // different hi on the same monster.
            if (ambiguousBase(o.name, o.base, o.hi)) {
                problems.push_back(std::string("val ambiguous ") + o.name + " base "
                                   + std::to_string(o.base));
                continue;
            }
            int applied = 0;
            for (auto& s : d->states)
                for (int f : kStateFields) {
                    int* p = fieldPtr(s, f);
                    if (p && *p == o.base && o.hi != o.base) { *p = o.hi; ++applied; }
                }
            for (int f = 7; f <= 8; ++f) {
                int* p = defFieldPtr(*d, f);
                if (p && *p == o.base && o.hi != o.base) { *p = o.hi; ++applied; }
            }
            if (applied == 0)
                problems.push_back(std::string("val: no match ") + o.name + " base "
                                   + std::to_string(o.base));
        }
    }
    if (!problems.empty() && !g_reported) {
        g_reported = true;
        std::fprintf(stderr, "sts2 ascension: %zu table problems (first 10):\n",
                     problems.size());
        for (std::size_t i = 0; i < problems.size() && i < 100; ++i)
            std::fprintf(stderr, "  %s\n", problems[i].c_str());
    }
}

