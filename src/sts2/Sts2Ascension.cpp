struct PristineDefs {
    std::vector<MonsterDef> defs;
};
PristineDefs* g_pristine = nullptr;
bool g_reported = false;

int* fieldPtr(MoveState& st, int field) {
    switch (field) {
        case 0: return &st.damage;
        case 1: return &st.selfBlock;
        case 2: return &st.selfPowerAmount;
        case 3: return &st.playerPowerAmount;
        case 4: return &st.playerPower2Amount;
        case 5: return &st.playerPower3Amount;
        case 6: return &st.healSelf;
        case 10: return &st.addCardToDiscardCount; // TestSubject BURNING_GROWL burn count
        case 11: return &st.hits;                   // A9 repeat counts (BEES/SKITTER/HOUNDS)
        case 12: return &st.addWithersToDiscard;    // Aeonglass INCREASING_INTENSITY withers
        default: return nullptr;
    }
}

// def-level fields: 7 startPowerAmount, 8 startPower2Amount, 9 startBlock
int* defFieldPtr(MonsterDef& d, int field) {
    switch (field) {
        case 7: return &d.startPowerAmount;
        case 8: return &d.startPower2Amount;
        case 9: return &d.startBlock;
        default: return nullptr;
    }
}

MonsterDef* findDef(std::vector<MonsterDef>& defs, const char* name) {
    for (auto& d : defs)
        if (std::strcmp(d.name, name) == 0) return &d;
    return nullptr;
}

bool ambiguousBase(const char* name, int base, int hi) {
    for (const AscValOverride& other : kAscVal) {
        if (std::strcmp(other.name, name) != 0 || other.base != base) continue;
        if (other.hi != hi) return true;
    }
    return false;
}

