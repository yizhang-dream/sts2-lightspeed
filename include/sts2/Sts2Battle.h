// ---------------- player ----------------
// Osty: the Necrobinder's summoned pet (MonsterModel with a single NOTHING_MOVE state).
// While alive it redirects powered attacks aimed at the owner onto itself
// (DieForYouPower.ModifyUnblockedDamageTarget); it is never removed from combat on death
// (ShouldCreatureBeRemovedFromCombatAfterDeath=false) so it can be revived by a later Summon.
struct OstyState {
    bool present = false;   // in combat (alive or dead-but-revivable)
    int curHp = 0;
    int maxHp = 0;
    int block = 0;
    std::vector<PowerInst> powers; // DieForYou + any buffs/debuffs Osty carries
    int combatId = 0;       // stamp osty field carries a combat id (0xFFFFFFFF when absent)
};

struct PlayerSide {
    int curHp = 80, maxHp = 80, block = 0;
    int energy = 0, maxEnergy = 3;
    int stars = 0;
    int gold = 0;
    std::vector<PowerInst> powers;
    std::array<int, 3> potions{};   // PotionId, 0 = empty (T1: parse/emit only)
    // Defect orb queue (OrbQueue): capacity from CharacterModel.BaseOrbSlotCount (Defect = 3),
    // orbs are FIFO; index 0 is the "next" orb (evoked first, Loop passive target).
    int orbCapacity = 0;
    std::vector<OrbInstance> orbs;
    OstyState osty;
    // Necrobinder resource: the Osty creature is its own actor; the player tracks it here
    // because single-player combat only ever has one pet.
    // BoundPhylactery (Necrobinder starter relic) re-summons Osty every energy reset late;
    // the relic list is not stamp-visible, so the root stamp's own pet presence is the
    // signal (osty=<cid>/hp/maxhp with a real cid).
    bool ownerHasBoundPhylactery = false;
    bool hasOsty() const { return osty.present; }
    bool isOstyAlive() const { return osty.present && osty.curHp > 0; }
    PowerInst* findPower(PowerId id);
};

