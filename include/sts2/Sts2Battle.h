// Move-state machine node (deterministic alternation + the T1/T2-family effect set).
struct MoveState {
    const char* moveId = "";
    int damage = 0;          // per-hit damage of the attack intent
    int hits = 1;
    int selfBlock = 0;       // EBB: monster gains block after attacking
    // applied power on self when executed (e.g. Bulk: +2 strength)
    PowerId selfPower = PowerId::NONE;
    int selfPowerAmount = 0;
    int next = -1;           // follow-up state idx (-1: stay)
    // applied power(s) on the player when executed (HAMMER: weak+frail; CONSTRICT: weak)
    PowerId playerPower = PowerId::NONE;
    int playerPowerAmount = 0;
    PowerId playerPower2 = PowerId::NONE;
    int playerPower2Amount = 0;
    PowerId playerPower3 = PowerId::NONE; // Queen YOU_ARE_MINE: frail+weak+vulnerable 99
    int playerPower3Amount = 0;
    // heal self when executed (REATTACH +25; -1 = heal to full for REVIVE)
    int healSelf = 0;
    // summon a monster (registry defIdx) into the given slot (FOGMOG ILLUSION)
    int summonDefIdx = -1;
    const char* summonSlot = "";
    int summonCount = 1;                 // Ovicopter LAY_EGGS summons 3 per execution
    bool summonLastFreeSlot = false;     // each summon takes the LAST free encounter slot
    // ConditionalBranchState evaluated on a predicate at intent-roll time
    // (Ovicopter SUMMON_BRANCH_STATE: CanLay = alive teammates <= 3)
    int condTrue = -1;
    int condFalse = -1;
    int condPredicate = 0;               // 1 = alive teammates <= 3
    // cards added to the player's HAND when executed (Myte TOXIC: 2x Toxic)
    CardId addCardToHand = CardId::INVALID;
    int addCardToHandCount = 0;
    // ThievingHopper: steal one deck card from the draw/discard piles (CombatCardGeneration
    // stream) and leave combat (ESCAPE_MOVE).
    bool stealCard = false;
    bool escapeCombat = false;
    // non-empty => this state is a RandomBranchState on the MonsterAi stream
    std::vector<BranchAlt> branch;
    // AEONGLASS INCREASING_INTENSITY compound effect
    bool upgradePlayerWithers = false;   // FakeUpgrade all Wither cards
    int addWithersToDiscard = 0;         // add N Wither cards to player discard
    int addDazedToDiscard = 0;           // EyeWithTeeth DISTRACT: 3x Dazed to discard bottom
    CardId addCardToDiscard = CardId::INVALID; // Slime Sticky Shot: Slimed to discard bottom
    int addCardToDiscardCount = 0;
    bool noLog = false;                  // forced states (REVIVE/DEAD/REATTACH) enter via
                                         // SetMoveImmediate and never join the StateLog
    bool slotInit = false;               // ConditionalBranchState resolved by slot parity
                                         // (Wriggler INIT: wriggler1/3 bite, 2/4 wriggle)
    // Kept at the END: BYRDONIS's MoveStates use positional aggregate initialization
    // ({id, damage, hits, selfBlock, selfPower, selfPowerAmount, next}).
    bool selfPowerAllies = false;        // apply selfPower to every living enemy (Obscura SAIL)
    bool hiveSpit = false;               // Entomancer PHEROMONE_SPIT: hive/strength split
    int addFranticToDraw = 0;            // Insatiable LIQUIFY: FranticEscape into the draw pile
    int addFranticToDiscard = 0;         // ... and into the discard pile (random positions)
    bool curseChoice = false;            // KnowledgeDemon CURSE_OF_KNOWLEDGE player choice
    // TheLost/TheForgotten DEBILITATING_SMOG / MIASMA: steal N Strength/Dexterity from the
    // player (the owner gains the same amount; Possess* hands it back on death).
    int stealStrength = 0;
    int stealDexterity = 0;
    // TheForgotten DREAD: damage = base + the owner's own Dexterity.
    bool damageAddsSelfDexterity = false;
    // TheForgotten MIASMA: GainBlock(8, ValueProp.Move) — the owner's Dexterity applies.
    bool selfBlockAddsSelfDexterity = false;
    // FrogKnight BEETLE_CHARGE sets HasBeetleCharged (drives the HALF_HEALTH branch).
    bool markBeetleCharged = false;
    // OwlMagistrate VERDICT: removes the owner's SoarPower before the debuff lands.
    bool removeSelfSoar = false;
    // Queen BURN_BRIGHT_FOR_ME: PowerCmd.Apply(GetTeammatesOf(owner) minus owner), then
    // 20 unpowered block on the owner.
    bool selfPowerTeammates = false;
    // Fabricator FabricateMove / FabricatingStrikeMove: 1 = defensive + aggro spawn,
    // 2 = aggro only. A spawn takes Encounter.GetNextSlot (first free encounter slot) and
    // skips the previous spawn (_lastSpawned).
    int fabricateKind = 0;
    // Guardbot GUARD_MOVE: 15 unpowered block to every Fabricator on the enemy side.
    bool guardFabricator = false;
    // Noisebot NOISE_MOVE: one Dazed to the discard bottom and one at a random position
    // in the draw pile.
    bool noisebotNoise = false;
    // TestSubject MULTI_CLAW: hit count = 3 + ExtraMultiClawCount (grows by 1 per use).
    bool hitsFromExtraClaw = false;
    // TestSubject RESPAWN_MOVE: revive stage (1 -> 200 HP + PainfulStabs; 2 -> 300 HP +
    // Nemesis, with Adaptable/PainfulStabs removed).
    bool testSubjectRespawn = false;
};

