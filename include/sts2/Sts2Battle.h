// sts2::BattleContext — T1 battle core for the STS2 port.
//
// Authority: data_private/sts2_decompiled (game source). Turn semantics:
//   - intents are rolled at PLAYER turn start (PrepareForNextTurn per enemy)
//   - player end turn = two phases (T1: hooks are no-ops, flush hand to discard)
//   - enemy phase executes each enemy's rolled intent
//   - AfterSideTurnEnd(enemy): Territorial→Strength etc., then debuff duration tick
//     (freshly applied PLAYER-side debuffs skip their first tick)
//   - next player turn: block clears (except the very first), energy resets, draw 5
//
// Damage pipeline mirrors Hook.ModifyDamageInternal with exact decimal semantics:
// additive (strength) -> multiplicative (weak 3/4, vulnerable 3/2) -> single final
// truncation per damage application. Implemented as integer rationals (num/den).
//
// State I/O contract = ContinuationStamp text (see Sts2Stamp.h).

