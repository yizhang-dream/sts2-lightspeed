// One orb in the queue. PassiveVal/EvokeVal are the STAMPED values (Focus applied at
// trigger time, not stored); Dark's evoke grows on each passive, Glass' passive decays.
struct OrbInstance {
    OrbKind kind = OrbKind::NONE;
    int darkEvoke = 6;   // DarkOrb._evokeVal accumulator (grows by PassiveVal per passive)
    int glassPassive = 4; // GlassOrb._passiveVal (decays by 1 per passive, floor 0)
    int upgrades = 0;    // stamp carries no orb upgrade; kept for symmetry
};

// Static card data — table-driven, generated by engine/tools/gen_sts2_tables.py
