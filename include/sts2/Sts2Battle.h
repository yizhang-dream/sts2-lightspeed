// PowerId comes from the generated Sts2PowerIds.h (full game power table,
// stamp names via powerStampName/powerIdFromStampName).

struct PowerInst {
    PowerId id = PowerId::NONE;
    int amount = 0;
    bool skipNextTick = false; // freshly applied player-side debuffs skip one tick
    int misc = -1;             // WITHERING_PRESENCE: CardsLeft counter (stamp dynamic var)
    // PowerInstanceType.Instanced powers (Panache/TheBomb/Flanking/Strangle/...): each
    // application is its OWN entry — the stamp prints one P= row per instance and they
    // never merge. `instanced` marks those; `aux` carries the per-instance secondary
    // value (Panache CardsLeft, TheBomb Damage).
    bool instanced = false;
    bool skipEnergyTick = false; // OrbitPower applied by the play being resolved: the
                                 // card's own cost was paid before the power existed
    int aux = -1;
};

