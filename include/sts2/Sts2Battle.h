struct CardStep {
    StepOp op = StepOp::NONE;
    int8_t varIdx = -1;         // CardDef::vars slot for the primary value (-1: constVal)
    int constVal = -1;          // constant primary value (or -1)
    int hits = 1;               // >0: hit count; <0: -(varSlot)-1 → hits from var slot
    PowerId power = PowerId::NONE; // for APPLY_POWER_*
    CalcKind calc = CalcKind::NONE;
    int8_t extraVarIdx = -1;    // ATTACK_CALC extra multiplier var slot
    CardId cardId = CardId::INVALID; // generated-token id (ADD_CARD_TO_HAND); INVALID = none
    int sign = 1;               // -1: negate the resolved amount (SharedFate/Friendship)
    std::uint8_t cond = 0;      // STEP_IF_* conditions (Spinner's upgraded channel)
};

struct CardDef {
    CardId id = CardId::INVALID;
    const char* name = "";
    CardType type = CardType::SKILL;
    int cost = 1;               // base energy cost (-1 = X/unplayable per flags)
    int costUp = 0;             // OnUpgrade EnergyCost.UpgradeBy
    int starCost = -1;          // -1 = none
    int maxUpgradeLevel = 1;    // 0 = cannot upgrade (statuses/curses)
    CardRarity rarity = CardRarity::COMMON;
    CardTarget target = CardTarget::SELF;
    std::uint16_t flags = 0;
    std::uint16_t flagsUpAdded = 0;   // keyword flags added by OnUpgrade (upgraded Scrawl: Retain)
    std::uint16_t flagsUpRemoved = 0; // keyword flags dropped by OnUpgrade (EchoForm/Chill)
    std::uint8_t tags = 0;
    std::uint8_t nVars = 0;
    CardVarSlot vars[5];
    std::uint8_t nSteps = 0;
    CardStep steps[8];

    bool hasFlag(unsigned f) const { return (flags & f) != 0; }
    bool hasTag(unsigned t) const { return (tags & t) != 0; }
};

